'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { tmp, copyDir, snapshot } = require('./helpers.js');
const root = path.resolve(__dirname, '..');
const script = path.join(root, 'build-vault.js');

function setup() {
  const dir = tmp();
  copyDir(path.join(root, 'sample-input'), path.join(dir, 'sample-input'));
  return { dir, cfg: path.join(dir, 'sample-input', 'config.json'), vault: path.join(dir, 'sample-vault') };
}
const run = (cfg, ...extra) => execFileSync(process.execPath, [script, '--config', cfg, ...extra], { encoding: 'utf8' });

test('idempotent: second run gives byte-identical output', () => {
  const { cfg, vault } = setup();
  run(cfg);
  const a = snapshot(vault);
  const mt = fs.statSync(path.join(vault, 'Dashboard.md')).mtimeMs;
  run(cfg);
  assert.deepStrictEqual(snapshot(vault), a);
  assert.strictEqual(fs.statSync(path.join(vault, 'Dashboard.md')).mtimeMs, mt, 'unchanged files are not rewritten');
});

test('a clean vault and a re-run vault are identical', () => {
  const x = setup(), y = setup();
  run(x.cfg); run(y.cfg); run(y.cfg);
  // file:/// links contain the temp path, so compare with it removed
  const norm = (c) => { const s = snapshot(c.vault); const o = {}; for (const k of Object.keys(s)) o[k] = fs.readFileSync(path.join(c.vault, k), 'utf8').split(c.dir.replace(/\\/g, '/')).join('<ROOT>'); return o; };
  assert.deepStrictEqual(norm(x), norm(y));
});

test('never edits input files and writes only inside the vault', () => {
  const { dir, cfg } = setup();
  const before = snapshot(path.join(dir, 'sample-input'));
  run(cfg);
  assert.deepStrictEqual(snapshot(path.join(dir, 'sample-input')), before);
  const top = fs.readdirSync(dir).sort();
  assert.deepStrictEqual(top, ['sample-input', 'sample-vault']);
});

test('expected notes, exclusions, statuses and counts', () => {
  const { cfg, vault } = setup();
  run(cfg);
  const has = (p) => fs.existsSync(path.join(vault, p));
  for (const p of ['Dashboard.md', '.obsidian/graph.json', 'Canvas/Overview.canvas', 'Projects/Project Alpha.md', 'Days/2026-11-24.md']) assert.ok(has(p), p);
  assert.ok(!has('Deliverables/old-draft.pdf.md'), '_to-delete excluded');
  assert.ok(!has('Deliverables/interview-footage.mp4.md'), 'raw footage excluded');
  assert.ok(!has('Deliverables/readme.html.md'), 'node_modules excluded');
  const fm = (n) => fs.readFileSync(path.join(vault, 'Projects', n + '.md'), 'utf8');
  assert.match(fm('Project Beta'), /status: blocked/);
  assert.match(fm('Project Gamma'), /status: done/);
  assert.match(fm('Project Alpha'), /delivered_count: 4/);
  assert.match(fm('Project Alpha'), /\[\[Project Beta\]\]/);
  assert.match(fm('Project Delta'), /last_touched: 2026-10-09/);
  const dash = fs.readFileSync(path.join(vault, 'Dashboard.md'), 'utf8');
  assert.match(dash, /```dataview/);
  assert.match(dash, /\| \[\[Project Delta\]\] \| active \| 2026-10-09 \| 49 \|/);
  const g = JSON.parse(fs.readFileSync(path.join(vault, '.obsidian/graph.json'), 'utf8'));
  assert.match(g.search, /^-tag:#day/);
  assert.strictEqual(g.colorGroups.length, 7);
  JSON.parse(fs.readFileSync(path.join(vault, 'Canvas/Overview.canvas'), 'utf8'));
});

test('every [[wikilink]] in the vault resolves to a note', () => {
  const { cfg, vault } = setup();
  run(cfg);
  const names = new Set();
  const files = [];
  const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const f = path.join(d, e.name); if (e.isDirectory()) { if (e.name !== '.obsidian') walk(f); } else if (f.endsWith('.md')) { files.push(f); names.add(e.name.slice(0, -3)); } } };
  walk(vault);
  for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(/\[\[([^\]|]+)\]\]/g)) assert.ok(names.has(m[1]), f + ' -> ' + m[1]);
});

test('owner notes are never touched and stale generated notes are removed', () => {
  const { cfg, vault } = setup();
  run(cfg);
  fs.mkdirSync(path.join(vault, 'Notes'), { recursive: true });
  fs.writeFileSync(path.join(vault, 'Notes', 'mine.md'), 'my note\n');
  fs.writeFileSync(path.join(vault, 'Projects', 'Mine.md'), 'owner file in generated folder\n');
  fs.writeFileSync(path.join(vault, 'Projects', 'Old.md'), 'x\n\n%% generated by build-vault.js, do not edit %%\n');
  run(cfg);
  assert.strictEqual(fs.readFileSync(path.join(vault, 'Notes', 'mine.md'), 'utf8'), 'my note\n');
  assert.ok(fs.existsSync(path.join(vault, 'Projects', 'Mine.md')));
  assert.ok(!fs.existsSync(path.join(vault, 'Projects', 'Old.md')));
});

test('--private-tags hides summary text, pending text, filenames for private projects', () => {
  const { cfg, vault } = setup();
  run(cfg, '--private-tags');
  const delta = fs.readFileSync(path.join(vault, 'Projects', 'Project Delta.md'), 'utf8');
  assert.match(delta, /pending_count: 3/);
  assert.doesNotMatch(delta, /survey/i);
  assert.doesNotMatch(delta, /## Summary/);
  assert.ok(!fs.existsSync(path.join(vault, 'Deliverables', 'survey-clean.csv.md')));
  const all = [];
  const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const f = path.join(d, e.name); if (e.isDirectory()) walk(f); else all.push(f); } };
  walk(vault);
  for (const f of all) assert.doesNotMatch(fs.readFileSync(f, 'utf8'), /survey/i, f);
});

test('copes with a project folder missing its log and an empty log', () => {
  const { dir, cfg, vault } = setup();
  fs.mkdirSync(path.join(dir, 'sample-input', 'projects', 'no-log'));
  fs.mkdirSync(path.join(dir, 'sample-input', 'projects', 'empty-log'));
  fs.writeFileSync(path.join(dir, 'sample-input', 'projects', 'empty-log', 'PROGRESS-LOG.md'), '');
  run(cfg);
  assert.ok(fs.existsSync(path.join(vault, 'Projects', 'Empty Log.md')));
  assert.ok(!fs.existsSync(path.join(vault, 'Projects', 'No Log.md')));
});

test('zero network: source imports no network or process modules', () => {
  const src = fs.readFileSync(script, 'utf8');
  assert.doesNotMatch(src, /require\(['"](https?|net|tls|dns|dgram|http2|child_process|worker_threads)['"]\)/);
  assert.doesNotMatch(src, /\bfetch\s*\(|XMLHttpRequest|WebSocket/);
  assert.deepStrictEqual([...src.matchAll(/require\(['"]([^'"]+)['"]\)/g)].map((m) => m[1]).sort(), ['fs', 'path']);
});
