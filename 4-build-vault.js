function renderCanvas(model) {
  const cols = ['active', 'waiting', 'blocked', 'done', 'parked'];
  const color = { active: '4', waiting: '3', blocked: '1' };
  const nodes = [], edges = [];
  const W = 280, H = 80, GAP = 20, PAD = 30;
  let x = 0;
  const idOf = {};
  for (const s of cols) {
    const ps = model.projects.filter((p) => p.status === s);
    const gh = PAD * 2 + Math.max(1, ps.length) * (H + GAP);
    nodes.push({ id: 'group-' + s, type: 'group', x, y: 0, width: W + PAD * 2, height: gh + 50, label: s.charAt(0).toUpperCase() + s.slice(1) + ' (' + ps.length + ')' });
    ps.forEach((p, i) => {
      const id = 'p-' + key(p.name);
      idOf[p.name] = id;
      const n = { id, type: 'file', file: 'Projects/' + p.name + '.md', x: x + PAD, y: 50 + PAD + i * (H + GAP), width: W, height: H };
      if (color[s]) n.color = color[s];
      nodes.push(n);
    });
    x += W + PAD * 2 + 60;
  }
  for (const p of model.projects) for (const r of p.related) if (idOf[p.name] && idOf[r]) edges.push({ id: 'e-' + key(p.name) + '-' + key(r), fromNode: idOf[p.name], toNode: idOf[r], fromSide: 'bottom', toSide: 'top' });
  return JSON.stringify({ nodes, edges }, null, 2) + '\n';
}

// ---------------------------------------------------------------- writing
function writeIfChanged(file, content, written) {
  written.add(path.resolve(file));
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file) && fs.readFileSync(file).equals(Buffer.from(content, 'utf8'))) return false;
  // Write a temp file and rename it over the target. A rename replaces the directory entry,
  // so a hard link to some other file is never written through.
  const tmpFile = file + '.tmp-' + process.pid;
  fs.writeFileSync(tmpFile, content, 'utf8');
  try { fs.renameSync(tmpFile, file); } catch (e) { try { fs.unlinkSync(tmpFile); } catch (e2) { /* ignore */ } throw e; }
  return true;
}
function ownedByUs(file) {
  try { return fs.readFileSync(file, 'utf8').trimEnd().endsWith(MARK); } catch (e) { return false; }
}


// ---------------------------------------------------------------- output safety
function realpathLoose(p) { // realpath of the nearest existing ancestor + the missing remainder
  let cur = path.resolve(p);
  const rest = [];
  for (;;) {
    try { return path.join(fs.realpathSync(cur), ...rest.reverse()); } catch (e) {
      const up = path.dirname(cur);
      if (up === cur) return path.resolve(p);
      rest.push(path.basename(cur)); cur = up;
    }
  }
}
function isInside(child, parent) {
  const rel = path.relative(parent, child);
  const same = process.platform === 'win32' ? rel === '' : rel === '';
  return same || (!!rel && !rel.startsWith('..') && !path.isAbsolute(rel));
}
function isLink(p) { try { return fs.lstatSync(p).isSymbolicLink(); } catch (e) { return false; } }
function preflight(cfg, model) {
  const vault = path.resolve(cfg.vaultDir);
  // 1. no symlink or junction anywhere in the output path below the config folder (or the vault itself)
  const base = isInside(vault, cfg.dir) ? cfg.dir : vault;
  const rel = path.relative(base, vault);
  let cur = base;
  const comps = rel ? rel.split(path.sep) : [];
  if (base === vault && isLink(vault)) throw new Error('Refusing to write: vault folder is a symlink or junction: ' + vault);
  for (const c of comps) {
    cur = path.join(cur, c);
    if (isLink(cur)) throw new Error('Refusing to write: output path contains a symlink or junction: ' + cur);
  }
  // 2. nothing inside the vault may be a symlink or junction (checked before any write)
  const walk = (d) => {
    let ents; try { ents = fs.readdirSync(d, { withFileTypes: true }); } catch (e) { return; }
    for (const e of ents) {
      const f = path.join(d, e.name);
      if (e.isSymbolicLink() || isLink(f)) throw new Error('Refusing to write: symlink or junction inside the vault: ' + f);
      if (e.isDirectory()) walk(f);
    }
  };
  if (fs.existsSync(vault)) walk(vault);
  // 3. the vault must not overlap any input
  const realVault = realpathLoose(vault);
  const inputs = [realpathLoose(cfg.file)];
  if (cfg.indexFile) inputs.push(realpathLoose(cfg.indexFile));
  for (const p of model.projects) inputs.push(realpathLoose(p.dir));
  for (const pat of cfg.scan) for (const d of globExpand(pat, cfg.dir)) if (fs.existsSync(path.join(d, 'PROGRESS-LOG.md'))) inputs.push(realpathLoose(d));
  for (const i of inputs) {
    if (isInside(realVault, i) || isInside(i, realVault)) throw new Error('Refusing to write: the vault overlaps an input (' + i + '). Choose a vaultDir outside your project folders, index and config.');
  }
}

function buildVault(cfg, opts = {}) {
  const model = buildModel(cfg, opts);
  preflight(cfg, model);
  const privMode = !!opts.privateTags;
  const vault = path.resolve(cfg.vaultDir);
  const written = new Set();
  const skippedOwner = [];
  const put = (rel, content, plain) => {
    const f = path.join(vault, rel);
    if (!plain && fs.existsSync(f) && !ownedByUs(f)) { skippedOwner.push(rel); return; }
    writeIfChanged(f, content, written);
  };
  const allDates = new Set();
  for (const p of model.projects) for (const d of p.dates) allDates.add(d);
  for (const p of model.projects) {
    const priv = privMode && p.private;
    put('Projects/' + p.name + '.md', renderProject(p, priv));
    if (!priv) for (const f of p.files) put('Deliverables/' + f.note + '.md', renderDeliverable(p, f));
  }
  for (const d of Array.from(allDates).sort()) put('Days/' + d + '.md', renderDay(d, model, privMode));
  put('Dashboard.md', renderDashboard(model, privMode));
  put('.obsidian/graph.json', renderGraph(), true);
  put('Canvas/Overview.canvas', renderCanvas(model), true);
  let removed = 0;
  for (const sub of ['Projects', 'Deliverables', 'Days']) {
    const d = path.join(vault, sub);
    if (!fs.existsSync(d)) continue;
    for (const n of fs.readdirSync(d)) {
      const f = path.join(d, n);
      if (!written.has(path.resolve(f)) && fs.statSync(f).isFile() && ownedByUs(f)) { fs.unlinkSync(f); removed++; }
    }
  }
  return { model, files: written.size, removed, skippedOwner };
}

// ---------------------------------------------------------------- watch
function watchSignature(cfg) {
  const parts = [];
  const add = (f) => { try { const s = fs.statSync(f); parts.push(f + ':' + s.mtimeMs + ':' + s.size); } catch (e) { parts.push(f + ':-'); } };
  for (const pat of cfg.scan) for (const d of globExpand(pat, cfg.dir)) add(path.join(d, 'PROGRESS-LOG.md'));
  if (cfg.indexFile) add(cfg.indexFile);
  return parts.join('|');
}
function watch(cfg, opts) {
  let sig = '';
  const run = () => {
    try { const r = buildVault(cfg, opts); console.log('[' + new Date().toISOString() + '] rebuilt: ' + r.model.projects.length + ' projects, ' + r.files + ' files'); }
    catch (e) { console.error('build failed: ' + e.message); }
  };
  const tick = () => { const s = watchSignature(cfg); if (s !== sig) { sig = s; run(); } };
  tick();
  console.log('Watching PROGRESS-LOG.md files and the index (checked every 2 s). Ctrl+C to stop.');
  return setInterval(tick, 2000);
}

// ---------------------------------------------------------------- cli
function main(argv) {
  const args = { config: null, watch: false, privateTags: false, asOf: null, help: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--config') args.config = argv[++i];
    else if (a === '--watch') args.watch = true;
    else if (a === '--private-tags') args.privateTags = true;
    else if (a === '--as-of') args.asOf = argv[++i];
    else if (a === '--help' || a === '-h') args.help = true;
    else { console.error('Unknown option: ' + a); process.exit(2); }
  }
  if (args.help || !args.config) {
    console.log('Usage: node build-vault.js --config config.json [--watch] [--as-of YYYY-MM-DD]');
    process.exit(args.help ? 0 : 2);
  }
  const cfg = loadConfig(args.config);
  const opts = { privateTags: args.privateTags, asOf: args.asOf };
  if (args.watch) { watch(cfg, opts); return; }
  let r;
  try { r = buildVault(cfg, opts); } catch (e) { console.error(e.message); process.exit(1); }
  console.log('Vault: ' + cfg.vaultDir + ' | ' + r.model.projects.length + ' projects, ' + r.files + ' files checked, ' + r.removed + ' stale removed');
  if (r.skippedOwner.length) console.warn('Skipped (owner notes with same names): ' + r.skippedOwner.join(', '));
}

