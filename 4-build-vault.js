#!/usr/bin/env node
'use strict';
/*
 * build-vault.js - turn plain-text PROGRESS-LOG.md files into an Obsidian vault.
 * Local only. No network calls, no telemetry, no dependencies (Node 18+).
 * Reads inputs, writes only inside the vault folder. Never edits or deletes inputs.
 */
const fs = require('fs');
const path = require('path');

const MARK = '%% generated by build-vault.js, do not edit %%';
const DELIVERABLE_EXT = new Set(['pdf', 'html', 'mp4', 'csv', 'docx', 'pptx', 'png']);
const SKIP_DIRS = new Set(['_to-delete', 'node_modules', '.git']);
const RAW_DIR = /^(raw|footage|rushes?|b-?roll|dailies|clips)$/i;
const RAW_FILE = /^(raw[-_ ]|footage|rush|mvi_|dsc_|gopr|vid_\d)/i;
const LABELS = { done: 'Done', decisions: 'Decisions', decision: 'Decisions', unverified: 'Unverified',
  next: 'Next', 'also built': 'Also built', delivered: 'Delivered' };
const STOP = new Set(('the a an and or of to in on for with by is are was were be been it its this that these those as at from '
  + 'into then than so if not no do does did done will can should could would we i you they he she our their my your '
  + 'need needs next also more still just up out over after before about via per').split(/\s+/));

// ---------------------------------------------------------------- text helpers
function normalizeText(s) {
  return String(s).replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
}
function stripMd(s) {
  return String(s)
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[\[([^\]|]*)\|([^\]]*)\]\]/g, '$2')
    .replace(/\[\[([^\]]*)\]\]/g, '$1')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/(\*\*|__|~~)/g, '')
    .replace(/(^|[\s(])[*_]([^*_]+)[*_]/g, '$1$2')
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
function oneLine(s, max) {
  s = String(s).replace(/\s+/g, ' ').trim();
  if (max && Array.from(s).length > max) s = Array.from(s).slice(0, max - 1).join('') + '\u2026';
  return s;
}
const IRREG = { wrote: 'write', written: 'write', built: 'build', made: 'make', sent: 'send', ran: 'run', began: 'begin', chose: 'choose', fixed: 'fix' };
function stem(t) {
  if (IRREG[t]) return IRREG[t];
  if (t.length > 5 && /ing$/.test(t)) return t.slice(0, -3);
  if (t.length > 4 && /ed$/.test(t)) return t.slice(0, -2);
  if (t.length > 4 && /es$/.test(t)) return t.slice(0, -2);
  if (t.length > 3 && /s$/.test(t) && !/ss$/.test(t)) return t.slice(0, -1);
  return t;
}
function tokens(s) {
  const out = new Set();
  for (const t of stripMd(s).toLowerCase().split(/[^\p{L}\p{N}]+/u)) {
    if (t.length >= 2 && !STOP.has(t)) out.add(stem(t));
  }
  return out;
}
function overlap(pending, done) {
  if (!pending.size) return 0;
  let n = 0;
  for (const t of pending) if (done.has(t)) n++;
  return n / pending.size;
}
function safeName(s) {
  const r = String(s).replace(/[\\/:*?"<>|#^\[\]]/g, '-').replace(/\s+/g, ' ').replace(/^[. ]+|[. ]+$/g, '').trim();
  return r || 'untitled';
}
function key(s) { return String(s).toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ''); }
function yq(s) { return JSON.stringify(String(s)); }
function yarr(a) { return '[' + a.map((x) => yq(x)).join(', ') + ']'; }
function cellEsc(s) { return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '); }
function humanSize(n) {
  if (n < 1024) return n + ' B';
  if (n < 1048576) return (n / 1024).toFixed(1) + ' KB';
  if (n < 1073741824) return (n / 1048576).toFixed(1) + ' MB';
  return (n / 1073741824).toFixed(2) + ' GB';
}
function isoDate(d) { return d.toISOString().slice(0, 10); }
function daysBetween(a, b) { // YYYY-MM-DD strings, b - a
  return Math.round((Date.parse(b + 'T00:00:00Z') - Date.parse(a + 'T00:00:00Z')) / 86400000);
}

// ---------------------------------------------------------------- log parser
function parseLog(text) {
  text = normalizeText(text);
  const lines = text.split('\n');
  const entries = [];
  let entry = null;
  let item = null;
  let cur = null;
  const labelRe = /^\s*(?:[-*+]\s+)?(?:\[[ xX]\]\s*)?\*\*\s*(Done|Decisions?|Unverified|Next|Also built|Delivered)\s*:?\s*\*\*\s*:?\s*(.*)$/i;
  const headRe = /^##\s+(\d{4}-\d{2}-\d{2})\b(.*)$/;
  const addItem = (text0) => {
    let t = text0.trim();
    let ticked = false;
    const m = /^\[([ xX])\]\s*(.*)$/.exec(t);
    if (m) { ticked = m[1].toLowerCase() === 'x'; t = m[2]; }
    if (!t) return;
    item = { text: t, ticked };
    cur.items.push(item);
  };
  let inFence = false;
  for (const raw of lines) {
    if (/^\s*(```|~~~)/.test(raw)) inFence = !inFence;
    const h = !inFence && headRe.exec(raw);
    if (h) {
      entry = { date: h[1], suffix: h[2].trim(), blocks: [], notes: [], index: entries.length };
      entries.push(entry); cur = null; item = null; continue;
    }
    if (!inFence && /^#{1,6}\s/.test(raw)) {
      if (/^#{1,2}\s/.test(raw)) entry = null;
      cur = null; item = null; continue;
    }
    if (!entry) continue;
    const l = !inFence && labelRe.exec(raw);
    if (l) {
      cur = { label: LABELS[l[1].toLowerCase()], items: [] };
      entry.blocks.push(cur);
      item = null;
      if (l[2].trim()) addItem(l[2]);
      continue;
    }
    if (!raw.trim()) continue;
    const b = /^(\s*)(?:[-*+]|\d+[.)])\s+(.*)$/.exec(raw);
    if (cur) {
      if (b) addItem(b[2]);
      else if (item) item.text += ' ' + raw.trim();
      else addItem(raw);
    } else if (b) {
      entry.notes.push(b[2].trim());
    } else {
      entry.notes.push(raw.trim());
    }
  }
  const done = [];
  const open = [];
  for (const e of entries) {
    for (const bl of e.blocks) {
      for (const it of bl.items) {
        if (bl.label === 'Done' || bl.label === 'Delivered' || bl.label === 'Also built') {
          done.push({ entry: e.index, tok: tokens(it.text) });
        } else if (bl.label === 'Next' || bl.label === 'Unverified') {
          open.push({ label: bl.label, text: it.text, entry: e.index, date: e.date, ticked: it.ticked, tok: tokens(it.text) });
        }
      }
    }
  }
  const pending = open.filter((p) => {
    if (p.ticked) return false;
    for (const d of done) if (d.entry > p.entry && overlap(p.tok, d.tok) >= 0.7) return false;
    return true;
  }).map((p) => ({ label: p.label, text: p.text, date: p.date }));
  return { entries, pending };
}

// ---------------------------------------------------------------- root index table
function splitRow(line) {
  const cells = [];
  let cur = '';
  let inCode = false;
  let link = 0;
  let s = line.trim();
  if (s.startsWith('|')) s = s.slice(1);
  if (s.endsWith('|') && !s.endsWith('\\|')) s = s.slice(0, -1);
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === '\\' && s[i + 1] === '|') { cur += '|'; i++; continue; }
    if (c === '`') inCode = !inCode;
    if (!inCode && c === '[' && s[i + 1] === '[') { link++; cur += '[['; i++; continue; }
    if (!inCode && c === ']' && s[i + 1] === ']' && link) { link--; cur += ']]'; i++; continue; }
    if (c === '|' && !inCode && !link) { cells.push(cur.trim()); cur = ''; continue; }
    cur += c;
  }
  cells.push(cur.trim());
  return cells;
}
function parseIndex(text) {
  const lines = normalizeText(text).split('\n');
  const rows = [];
  let cols = null;
  for (const ln of lines) {
    if (!/^\s*\|/.test(ln)) { if (cols && rows.length && ln.trim()) cols = null; continue; }
    const cells = splitRow(ln);
    if (!cols) {
      const low = cells.map((c) => stripMd(c).toLowerCase());
      const p = low.indexOf('project'), s = low.indexOf('stage'), l = low.indexOf('last touched'), n = low.indexOf('next action');
      if (p >= 0 && s >= 0 && l >= 0 && n >= 0) cols = { p, s, l, n, last: n === low.length - 1 };
      continue;
    }
    if (cells.every((c) => /^:?-+:?$/.test(c.replace(/\s/g, '')) || c === '')) continue;
    rows.push({ project: stripMd(cells[cols.p] || ''), stage: stripMd(cells[cols.s] || ''),
      lastTouched: stripMd(cells[cols.l] || ''), nextAction: stripMd(cols.last ? cells.slice(cols.n).join(' | ') : (cells[cols.n] || '')) });
  }
  return rows;
}

// ---------------------------------------------------------------- filesystem scan
function globExpand(pattern, baseDir) {
  const segs = pattern.replace(/\\/g, '/').split('/').filter((s, i) => s !== '' || i === 0);
  let start;
  if (/^[A-Za-z]:$/.test(segs[0])) start = segs.shift() + '/';
  else if (segs[0] === '') { start = '/'; segs.shift(); }
  else start = baseDir;
  let cur = [start];
  for (const seg of segs) {
    const next = [];
    if (/[*?]/.test(seg)) {
      const re = new RegExp('^' + seg.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*+/g, '.*').replace(/\?/g, '.') + '$', 'i');
      for (const c of cur) {
        let names = [];
        try { names = fs.readdirSync(c); } catch (e) { continue; }
        for (const n of names.sort()) if (re.test(n)) next.push(path.join(c, n));
      }
    } else {
      for (const c of cur) next.push(path.join(c, seg));
    }
    cur = next;
  }
  return cur.filter((d) => { try { return fs.statSync(d).isDirectory(); } catch (e) { return false; } });
}
function walkDeliverables(root, skipDirs, rel = '') {
  const out = [];
  let ents;
  try { ents = fs.readdirSync(path.join(root, rel), { withFileTypes: true }); } catch (e) { return out; }
  ents.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const e of ents) {
    const r = rel ? rel + '/' + e.name : e.name;
    const full = path.join(root, r);
    if (e.isSymbolicLink()) continue;
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name) || RAW_DIR.test(e.name) || skipDirs.has(path.resolve(full))) continue;
      out.push(...walkDeliverables(root, skipDirs, r));
    } else if (e.isFile()) {
      const ext = path.extname(e.name).slice(1).toLowerCase();
      if (!DELIVERABLE_EXT.has(ext)) continue;
      if (ext === 'mp4' && RAW_FILE.test(e.name)) continue;
      let st; try { st = fs.statSync(full); } catch (er) { continue; }
      out.push({ rel: r, full, name: e.name, ext, size: st.size, date: isoDate(st.mtime) });
    }
  }
  return out;
}
function fileUrl(abs) {
  let p = abs.replace(/\\/g, '/');
  let drive = '';
  const m = /^([A-Za-z]:)(\/.*)?$/.exec(p);
  if (m) { drive = m[1]; p = m[2] || '/'; }
  p = p.replace(/^\/+/, '');
  const enc = p.split('/').map((s) => encodeURIComponent(s).replace(/[()]/g, (c) => (c === '(' ? '%28' : '%29'))).join('/');
  return 'file:///' + (drive ? drive + '/' : '') + enc;
}

// ---------------------------------------------------------------- model building
function loadConfig(cfgPath) {
  const raw = JSON.parse(normalizeText(fs.readFileSync(cfgPath, 'utf8')));
  const dir = path.dirname(path.resolve(cfgPath));
  const abs = (p) => (p == null ? p : (path.isAbsolute(p) || /^[A-Za-z]:[\\/]/.test(p) ? p : path.resolve(dir, p)));
  return {
    dir,
    file: path.resolve(cfgPath),
    scan: raw.scan || [],
    indexFile: abs(raw.indexFile || null),
    vaultDir: abs(raw.vaultDir || 'vault'),
    staleDays: Number.isFinite(raw.staleDays) ? raw.staleDays : 14,
    recentDays: Number.isFinite(raw.recentDays) ? raw.recentDays : 7,
    asOf: raw.asOf || null,
    projectTags: raw.projectTags || {},
  };
}

function classify(stageText, nextText) {
  const stage = (stageText || '').toLowerCase();
  const next = (nextText || '').toLowerCase();
  if (/\b(done|wrapped|complete[d]?|shipped)\b/.test(stage)) return 'done';
  if (/\b(parked|paused|on hold|shelved)\b/.test(stage)) return 'parked';
  if (/\b(needs?|waiting on|blocked)\b/.test(next)) return 'blocked';
  if (/\bblocked\b/.test(stage)) return 'blocked';
  if (/\bwaiting\b/.test(stage)) return 'waiting';
  return 'active';
}

function buildModel(cfg, opts = {}) {
  const today = isoDate(new Date(Date.now() - new Date().getTimezoneOffset() * 60000));
  const asOf = opts.asOf || cfg.asOf || today;
  const indexRows = cfg.indexFile && fs.existsSync(cfg.indexFile) ? parseIndex(fs.readFileSync(cfg.indexFile, 'utf8')) : [];
  const dirs = [];
  const seen = new Set();
  for (const pat of cfg.scan) for (const d of globExpand(pat, cfg.dir)) {
    const r = path.resolve(d);
    if (!seen.has(r)) { seen.add(r); dirs.push(r); }
  }
  dirs.sort();
  const vaultAbs = path.resolve(cfg.vaultDir);
  const projects = [];
  const usedNames = new Set();
  for (const dir of dirs) {
    if (dir === vaultAbs) continue;
    const logPath = path.join(dir, 'PROGRESS-LOG.md');
    if (!fs.existsSync(logPath)) continue;
    const logText = normalizeText(fs.readFileSync(logPath, 'utf8'));
    const parsed = parseLog(logText);
    const base = path.basename(dir);
    const humanized = base.replace(/[-_]+/g, ' ').replace(/\s+/g, ' ').trim().replace(/\b\p{L}/gu, (c) => c.toUpperCase());
    const idx = indexRows.find((r) => key(r.project) === key(base) || key(r.project) === key(humanized));
    let name = safeName(idx ? idx.project : humanized);
    let n = 2; const nm = name;
    while (usedNames.has(name.toLowerCase())) name = nm + ' (' + (n++) + ')';
    usedNames.add(name.toLowerCase());
    const files = walkDeliverables(dir, new Set([vaultAbs]));
    const dates = parsed.entries.map((e) => e.date).sort();
    let newestNext = '';
    let firstNext = '';
    for (let i = parsed.entries.length - 1; i >= 0 && !newestNext; i--) {
      for (const bl of parsed.entries[i].blocks) if (bl.label === 'Next' && bl.items.length) {
        newestNext = bl.items.map((x) => x.text).join(' ; ');
        firstNext = bl.items[0].text;
        break;
      }
    }
    const idxDate = idx && /\d{4}-\d{2}-\d{2}/.exec(idx.lastTouched);
    const lastTouched = dates.length ? dates[dates.length - 1] : (idxDate ? idxDate[0] : (files.length ? files.map((f) => f.date).sort().pop() : ''));
    const status = classify(idx && idx.stage, newestNext || (idx && idx.nextAction) || '');
    const nextAction = oneLine(stripMd(firstNext || (idx && idx.nextAction) || ''), 300);
    const tags = ['project', 'status/' + status];
    for (const t of (cfg.projectTags[name] || cfg.projectTags[base] || [])) if (!tags.includes(t)) tags.push(t);
    projects.push({ name, base, dir, parsed, files, dates, latest: parsed.entries.length ? parsed.entries[parsed.entries.length - 1] : null,
      lastTouched, status, nextAction, tags, private: tags.includes('private'), logText });
  }
  projects.sort((a, b) => (a.name.toLowerCase() < b.name.toLowerCase() ? -1 : a.name.toLowerCase() > b.name.toLowerCase() ? 1 : 0));
  const nameCount = {};
  for (const p of projects) for (const f of p.files) nameCount[f.name.toLowerCase()] = (nameCount[f.name.toLowerCase()] || 0) + 1;
  const used = new Set();
  for (const p of projects) for (const f of p.files) {
    let nm = safeName(f.name);
    if (nameCount[f.name.toLowerCase()] > 1 || used.has(nm.toLowerCase())) nm = safeName(p.name + ' - ' + f.rel.replace(/\//g, ' - '));
    let k = 2; const b = nm;
    while (used.has(nm.toLowerCase())) nm = b + ' (' + (k++) + ')';
    used.add(nm.toLowerCase());
    f.note = nm;
  }
  for (const p of projects) {
    const hay = p.logText.toLowerCase();
    p.related = [];
    for (const q of projects) {
      if (q === p) continue;
      const names = new Set([q.name.toLowerCase(), q.base.toLowerCase(), q.base.replace(/[-_]+/g, ' ').toLowerCase()]);
      for (const nm of names) {
        if (nm.length < 3) continue;
        const re = new RegExp('(^|[^\\p{L}\\p{N}])' + nm.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\s+/g, '[\\s_-]+') + '($|[^\\p{L}\\p{N}])', 'u');
        if (re.test(hay)) { p.related.push(q.name); break; }
      }
    }
  }
  return { projects, asOf, cfg };
}

// ---------------------------------------------------------------- rendering
function summaryLines(p) {
  const lines = [];
  const order = ['Done', 'Also built', 'Delivered', 'Decisions', 'Next', 'Unverified'];
  const push = (label, text) => { if (lines.length < 5) lines.push('- **' + label + ':** ' + oneLine(stripMd(text), 220)); };
  const e = p.latest;
  if (e) {
    for (const lab of order) for (const bl of e.blocks) if (bl.label === lab) for (const it of bl.items) push(lab, it.text);
    if (lines.length < 3) for (const n of e.notes) push('Note', n);
    for (let i = p.parsed.entries.length - 2; i >= 0 && lines.length < 3; i--) {
      for (const bl of p.parsed.entries[i].blocks) if (bl.label === 'Done') for (const it of bl.items) if (lines.length < 3) push('Earlier', it.text);
    }
  }
  if (!lines.length) lines.push('- No log entries yet.');
  return lines;
}

function renderProject(p, priv) {
  const out = [];
  const pc = p.parsed.pending.length;
  out.push('---');
  out.push('project: ' + yq(p.name));
  out.push('status: ' + p.status);
  out.push('last_touched: ' + (p.lastTouched || ''));
  out.push('next_action: ' + yq(priv ? '' : p.nextAction));
  out.push('pending_count: ' + pc);
  out.push('delivered_count: ' + p.files.length);
  out.push('tags: ' + yarr(p.tags));
  out.push('---');
  out.push('# ' + p.name);
  out.push('');
  if (priv) {
    out.push('Private project. ' + pc + ' pending, ' + p.files.length + ' delivered. Status: ' + p.status + '.');
  } else {
    out.push('## Summary');
    out.push(...summaryLines(p));
    out.push('');
    out.push('## Pending');
    if (!pc) out.push('Nothing pending.');
    for (const it of p.parsed.pending) out.push('- [ ] ' + oneLine(stripMd(it.text), 400) + ' (' + it.label + ', [[' + it.date + ']])');
    out.push('');
    out.push('## Delivered');
    if (!p.files.length) out.push('No deliverable files found.');
    for (const f of p.files) out.push('- [[' + f.note + ']]');
    out.push('');
    out.push('## Timeline');
    const ds = Array.from(new Set(p.dates)).sort().reverse();
    if (!ds.length) out.push('No dated log entries.');
    for (const d of ds) out.push('- [[' + d + ']]');
  }
  out.push('');
  out.push('## Related');
  if (!p.related.length) out.push('None detected.');
  for (const r of p.related) out.push('- [[' + r + ']]');
  out.push('');
  out.push(MARK);
  return out.join('\n') + '\n';
}

function renderDeliverable(p, f) {
  return ['---', 'type: ' + f.ext, 'date: ' + f.date, 'size: ' + yq(humanSize(f.size)), 'size_bytes: ' + f.size,
    'project: ' + yq('[[' + p.name + ']]'), 'tags: ' + yarr(['deliverable', 'type/' + f.ext]), '---',
    '# ' + f.name, '', '- Type: ' + f.ext, '- Date: ' + f.date, '- Size: ' + humanSize(f.size),
    '- Project: [[' + p.name + ']]', '- Open: [' + f.name.replace(/[\[\]]/g, '') + '](' + fileUrl(f.full) + ')', '', MARK, ''].join('\n');
}

function renderDay(date, model, privMode) {
  const out = ['---', 'date: ' + date, 'tags: ["day"]', '---', '# ' + date, ''];
  let any = false;
  for (const p of model.projects) {
    const es = p.parsed.entries.filter((e) => e.date === date);
    if (!es.length) continue;
    any = true;
    const priv = privMode && p.private;
    out.push('## [[' + p.name + ']]');
    if (priv) { out.push('Private project.'); out.push(''); continue; }
    for (const e of es) {
      for (const bl of e.blocks) for (const it of bl.items) out.push('- **' + bl.label + ':** ' + oneLine(stripMd(it.text), 300));
      for (const n of e.notes) out.push('- ' + oneLine(stripMd(n), 300));
    }
    const fs2 = p.files.filter((f) => f.date === date);
    if (fs2.length) { out.push(''); out.push('Deliverables: ' + fs2.map((f) => '[[' + f.note + ']]').join(', ')); }
    out.push('');
  }
  if (!any) out.push('No entries.');
  out.push(MARK);
  return out.join('\n') + '\n';
}

function renderDashboard(model, privMode) {
  const { projects, asOf, cfg } = model;
  const stale = cfg.staleDays, recent = cfg.recentDays;
  const vis = (p) => !(privMode && p.private);
  const out = ['---', 'tags: ["dashboard"]', '---', '# Dashboard', '',
    'As of ' + asOf + '. The Dataview tables update live in Obsidian. The static tables below each one are a snapshot from the last build, for use without the plugin.', ''];
  const dv = (q) => ['```dataview', q, '```', ''];
  out.push('## Pending by project', '', ...dv('TABLE WITHOUT ID file.link AS Project, status AS Status, pending_count AS Pending, next_action AS "Next action"\nFROM "Projects"\nWHERE pending_count > 0\nSORT pending_count DESC'));
  out.push('Static:', '', '| Project | Status | Pending | Next action |', '| --- | --- | --- | --- |');
  const pend = projects.filter((p) => p.parsed.pending.length > 0).sort((a, b) => b.parsed.pending.length - a.parsed.pending.length || (a.name < b.name ? -1 : 1));
  for (const p of pend) out.push('| [[' + p.name + ']] | ' + p.status + ' | ' + p.parsed.pending.length + ' | ' + (vis(p) ? cellEsc(oneLine(p.nextAction, 160)) : '') + ' |');
  if (!pend.length) out.push('| None | | | |');
  out.push('');
  out.push('## Delivered in the last ' + recent + ' days', '', ...dv('TABLE WITHOUT ID file.link AS Deliverable, type AS Type, date AS Date, project AS Project\nFROM "Deliverables"\nWHERE date >= date(today) - dur(' + recent + ' days)\nSORT date DESC'));
  out.push('Static:', '', '| Deliverable | Type | Date | Project |', '| --- | --- | --- | --- |');
  const rec = [];
  for (const p of projects) if (vis(p)) for (const f of p.files) { const d = daysBetween(f.date, asOf); if (d >= 0 && d <= recent) rec.push({ p, f }); }
  rec.sort((a, b) => (a.f.date < b.f.date ? 1 : a.f.date > b.f.date ? -1 : a.f.note < b.f.note ? -1 : 1));
  for (const r of rec) out.push('| [[' + r.f.note + ']] | ' + r.f.ext + ' | ' + r.f.date + ' | [[' + r.p.name + ']] |');
  if (!rec.length) out.push('| None | | | |');
  out.push('');
  out.push('## Stale (no entry for ' + stale + '+ days)', '', ...dv('TABLE WITHOUT ID file.link AS Project, status AS Status, last_touched AS "Last touched"\nFROM "Projects"\nWHERE status != "done" AND status != "parked" AND date(today) - date(last_touched) >= dur(' + stale + ' days)\nSORT last_touched ASC'));
  out.push('Static:', '', '| Project | Status | Last touched | Days quiet |', '| --- | --- | --- | --- |');
  const st = projects.filter((p) => p.status !== 'done' && p.status !== 'parked' && p.lastTouched && daysBetween(p.lastTouched, asOf) >= stale)
    .sort((a, b) => (a.lastTouched < b.lastTouched ? -1 : a.lastTouched > b.lastTouched ? 1 : a.name < b.name ? -1 : 1));
  for (const p of st) out.push('| [[' + p.name + ']] | ' + p.status + ' | ' + p.lastTouched + ' | ' + daysBetween(p.lastTouched, asOf) + ' |');
  if (!st.length) out.push('| None | | | |');
  out.push('');
  out.push('## Blocked and waiting', '', ...dv('TABLE WITHOUT ID file.link AS Project, status AS Status, next_action AS "Next action"\nFROM "Projects"\nWHERE status = "blocked" OR status = "waiting"\nSORT status ASC'));
  out.push('Static:', '', '| Project | Status | Next action |', '| --- | --- | --- |');
  const bw = projects.filter((p) => p.status === 'blocked' || p.status === 'waiting');
  for (const p of bw) out.push('| [[' + p.name + ']] | ' + p.status + ' | ' + (vis(p) ? cellEsc(oneLine(p.nextAction, 160)) : '') + ' |');
  if (!bw.length) out.push('| None | | |');
  out.push('');
  out.push('## Counts per status', '', ...dv('TABLE WITHOUT ID status AS Status, length(rows) AS Projects\nFROM "Projects"\nGROUP BY status'));
  out.push('Static:', '', '| Status | Projects |', '| --- | --- |');
  for (const s of ['active', 'waiting', 'blocked', 'done', 'parked']) out.push('| ' + s + ' | ' + projects.filter((p) => p.status === s).length + ' |');
  out.push('');
  out.push(MARK);
  return out.join('\n') + '\n';
}

